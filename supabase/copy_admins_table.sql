-- Run this in the OLD project's SQL Editor. It writes nothing there; it only builds one line of SQL.
-- Copy the single result cell and run it in the NEW project's SQL Editor. It recreates public.admins with
-- the same columns and rows, locked so the website and its public key can't read it.
-- Passwords stay out of this file. The result contains them, so don't save it or commit it.
WITH cols AS (
  SELECT a.attnum, format('%I %s%s%s', a.attname, format_type(a.atttypid, a.atttypmod),
    CASE WHEN pg_get_expr(d.adbin, d.adrelid) LIKE 'nextval(%' THEN ' GENERATED BY DEFAULT AS IDENTITY'
         WHEN d.adbin IS NOT NULL THEN ' DEFAULT ' || pg_get_expr(d.adbin, d.adrelid) ELSE '' END,
    CASE WHEN a.attnotnull AND coalesce(pg_get_expr(d.adbin, d.adrelid), '') NOT LIKE 'nextval(%' THEN ' NOT NULL' ELSE '' END) AS col
  FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
  WHERE a.attrelid = 'public.admins'::regclass AND a.attnum > 0 AND NOT a.attisdropped
), cons AS (
  SELECT pg_get_constraintdef(oid) AS def FROM pg_constraint WHERE conrelid = 'public.admins'::regclass AND contype IN ('p', 'u')
)
SELECT 'BEGIN; CREATE TABLE IF NOT EXISTS public.admins ('
  || (SELECT string_agg(col, ', ' ORDER BY attnum) FROM cols)
  || coalesce((SELECT ', ' || string_agg(def, ', ') FROM cons), '')
  || '); ALTER TABLE public.admins ENABLE ROW LEVEL SECURITY; REVOKE ALL ON public.admins FROM anon, authenticated; '
  || format('INSERT INTO public.admins SELECT * FROM jsonb_populate_recordset(NULL::public.admins, %L::jsonb) ON CONFLICT DO NOTHING; ',
       (SELECT coalesce(jsonb_agg(to_jsonb(a)), '[]'::jsonb) FROM public.admins a)::text)
  || 'COMMIT;' AS run_this_in_the_new_project;
